head("S3  the information limit: n samples, d dimensions, smoothness s")


def s3_nwidth() -> dict:
    out()
    out("  derivation (the whole argument, in five lines)")
    out("    (i)   f has a Fourier series f = sum_k c_k e^{2 pi i k.x} on [0,1]^d.")
    out("    (ii)  being in the Sobolev class H^s means  sum_k |k|^{2s} |c_k|^2 <= 1.")
    out("    (iii) n samples give n linear equations, so at most n coefficients can be")
    out("          pinned down: the resolvable bandwidth B is where the lattice count")
    out("          N(B) := #{k in Z^d : |k|_1 <= B} first exceeds n, and N(B) ~ c B^d,")
    out("          so B ~ n^{1/d};")
    out("    (iv)  the worst case over the Sobolev ball puts all the tail energy on the")
    out("          first shell outside B, where |k| = B+1, so the leftover L2 error is")
    out("          at most (B+1)^{-2s};")
    out("    (v)   => best possible RMSE  E_n ~ (B+1)^{-s} ~ n^{-s/d}.")
    out()
    out("  the constants are irrelevant for the argument; the EXPONENT is the content,")
    out("  and the exponent is a counting statement, so it can be CHECKED exactly:")
    out()

    def shell_count_closed(d: int, r: int) -> int:
        """#{k in Z^d : |k|_1 = r} = sum_j C(d,j) 2^j C(r-1,j-1)."""
        if r == 0:
            return 1
        tot = 0
        for j in range(1, min(d, r) + 1):
            tot += math.comb(d, j) * (2 ** j) * math.comb(r - 1, j - 1)
        return tot

    def shell_count_brute(d: int, r: int) -> int:
        cnt = 0
        for k in itertools.product(range(-r, r + 1), repeat=d):
            if sum(abs(v) for v in k) == r:
                cnt += 1
        return cnt

    out("  the counting formula, checked against brute force:")
    for d, r in ((1, 3), (2, 4), (3, 3), (2, 6)):
        a, b = shell_count_closed(d, r), shell_count_brute(d, r)
        out(f"    d = {d}, r = {r}: closed form {a:5d} | brute force {b:5d} |"
            f" {'match' if a == b else 'MISMATCH'}")
    out()

    def cumulative(d: int, B: int) -> int:
        return sum(shell_count_closed(d, r) for r in range(B + 1))

    cases = [(2, 1), (2, 2), (2, 4), (4, 2), (1, 2)]
    ns = [16, 64, 256, 1024, 4096]
    out("  B(n) = largest bandwidth with N(B) <= n, and the resulting RMSE bound")
    out("  s   d |  predicted -s/d |  measured slope  |  ratio  | B(n) at n = 16..4096")
    out("  " + "-" * 96)
    slopes = {}
    for s, d in cases:
        vals, bs = [], []
        for n in ns:
            B = 0
            while cumulative(d, B + 1) <= n:
                B += 1
            bs.append(B)
            vals.append((B + 1) ** (-float(s)))
        xs = np.log(np.array(ns, dtype=float))
        ys = np.log(np.array(vals, dtype=float))
        slope = float(np.polyfit(xs, ys, 1)[0])
        slopes[f"s{s}_d{d}"] = slope
        out(f"  {s}   {d} |      {-s/d:+.4f}      |     {slope:+.4f}      |"
            f" {slope/(-s/d):.3f}  | {bs}")
    out("  " + "-" * 96)
    out()
    out("  the same statement in kernel language: for a kernel with eigenvalues")
    out("  lam_1 >= lam_2 >= ..., the n-width is E_n = sqrt(lam_{n+1}).  A Gaussian kernel")
    out("  on [0,1] has a spectrum that decays faster than any power, so its E_n decays")
    out("  faster than any power of n as well:")
    xg = np.linspace(0, 1, 256)[:, None]
    Kg = np.exp(-0.5 * ((xg - xg.T) / 0.15) ** 2)
    ev = np.linalg.eigvalsh(Kg)[::-1]
    out("    n      lam_{n+1}       sqrt(lam_{n+1})")
    floor = np.finfo(float).eps * max(Kg.shape) * ev[0]
    for n in (8, 16, 32, 64, 128, 256):
        lam_n1 = float(ev[n]) if n < len(ev) else 0.0
        tag = "   <- numerical floor" if lam_n1 <= floor else ""
        out(f"    {n:4d}   {lam_n1:.4e}   {math.sqrt(max(lam_n1, 0.0)):.4e}{tag}")
    out("    (below the floor the eigenvalues are numerical noise, so the tail of this")
    out("     table says 'faster than any power', not a specific rate)")
    result["S3"] = dict(slopes=slopes, cases=[list(c) for c in cases],
                         gaussian_sqrt_lambda={
                             str(n): math.sqrt(float(ev[n])) if n < len(ev) else 0.0
                             for n in (8, 16, 32, 64, 128, 256)})
    return slopes


s3_nwidth()

