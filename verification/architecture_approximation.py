def _comps(total: int, parts: int):
    """Weak compositions of `total` into `parts` parts."""
    if parts == 1:
        yield (total,)
        return
    for first in range(total + 1):
        for rest in _comps(total - first, parts - 1):
            yield (first,) + rest


def multi_indices(d: int, deg: int) -> list[tuple[int, ...]]:
    """All multi-indices with total degree <= deg (exactly comb(d+deg, d) of them).

    Generated by composition: iterating itertools.product(range(deg+1), repeat=d)
    would be (deg+1)^d steps, which is hopeless for d = 16.
    """
    idx: list[tuple[int, ...]] = []
    for total in range(deg + 1):
        idx.extend(_comps(total, d))
    return idx


class Cheb:
    """Total-degree Chebyshev basis on the observed box.

    Built from the stable recurrence T_{k+1} = 2 t T_k - T_{k-1}.  (The form
    cos(k pi t) is NOT usable here: it spans only functions that are even about
    t = 0, so sin(2 pi x) would be orthogonal to the whole basis.)
    """

    def __init__(self, deg: int, lo: np.ndarray, hi: np.ndarray) -> None:
        self.deg = deg
        self.lo = np.asarray(lo, dtype=float)
        self.hi = np.asarray(hi, dtype=float)
        rng = self.hi - self.lo
        rng[rng == 0] = 1.0
        self.scale = rng

    def __call__(self, X: np.ndarray) -> np.ndarray:
        d = X.shape[1]
        axes = []
        for ax in range(d):
            t = 2.0 * (X[:, ax] - self.lo[ax]) / self.scale[ax] - 1.0
            polys = [np.ones(len(t)), t]
            for _ in range(2, self.deg + 1):
                polys.append(2.0 * t * polys[-1] - polys[-2])
            axes.append(polys)
        cols = [np.ones(len(X))]
        for multi in multi_indices(d, self.deg):
            if sum(multi) == 0:
                continue
            c = np.ones(len(X))
            for ax, k in enumerate(multi):
                c = c * axes[ax][k]
            cols.append(c)
        return np.stack(cols, axis=1)


def poly_class(X: np.ndarray, m: int, lo=None, hi=None) -> tuple[np.ndarray, int]:
    """Total-degree polynomial class with at most m basis functions; returns (Phi, deg)."""
    d = X.shape[1]
    if lo is None:
        lo = X.min(axis=0)
        hi = X.max(axis=0)
    deg = max(1, m - 1)
    while deg > 1 and math.comb(d + deg, d) > m:
        deg -= 1
    return Cheb(deg, lo, hi)(X), deg


def relu_class(X: np.ndarray, m: int, seed: int, lo=None, hi=None) -> np.ndarray:
    """Random one-hidden-layer ReLU features: the infinite-width (lazy) limit of a layer."""
    rng = np.random.default_rng(seed)
    d = X.shape[1]
    if lo is None:
        lo = X.min(axis=0)
        hi = X.max(axis=0)
    rng_ = hi - lo
    rng_[rng_ == 0] = 1.0
    Z = (X - lo) / rng_
    W = rng.normal(size=(d, m))
    b = rng.normal(size=m)
    return np.maximum(Z @ W + b, 0.0)


def addit_class(X: np.ndarray, m: int, seed: int, lo=None, hi=None) -> np.ndarray:
    """Axis-aligned random ReLU features: the classic (Barron-style) additive class."""
    if X.shape[1] == 1:
        return relu_class(X, m, seed, lo, hi)      # in 1-D the two classes coincide
    rng = np.random.default_rng(seed)
    d = X.shape[1]
    if lo is None:
        lo = X.min(axis=0)
        hi = X.max(axis=0)
    rng_ = hi - lo
    rng_[rng_ == 0] = 1.0
    Z = (X - lo) / rng_
    W = np.zeros((d, m))
    idx = rng.integers(0, d, size=m)
    W[idx, np.arange(m)] = rng.normal(size=m)
    b = rng.normal(size=m)
    return np.maximum(Z @ W + b, 0.0)


def proj_error(Phi: np.ndarray, f: np.ndarray) -> tuple[float, float]:
    """Squared L2 error of the ORTHOGONAL PROJECTION of f onto span(Phi).

    Computed with a QR factorisation, so the answer is the projection error and not
    the error of a numerically truncated normal-equation solve.
    """
    Q, _ = np.linalg.qr(Phi, mode="reduced")
    resid = f - Q @ (Q.T @ f)
    sse = float(resid @ resid)
    rel = float(math.sqrt(sse / max(float(f @ f), 1e-30)))
    return sse, rel


def ridge_label_eval(Phi_tr, y_tr, Phi_te, y_te, ridges):
    """Pick the ridge by LOO on the training set, then report train/test accuracy."""
    n = len(y_tr)
    K = Phi_tr @ Phi_tr.T
    best = None
    for lam in ridges:
        Ki = np.linalg.inv(K + lam * np.eye(n))
        alpha = Ki @ y_tr
        yhat = K @ alpha
        h = 1.0 - lam * np.diag(Ki)
        loo = (y_tr - yhat) / np.clip(1.0 - h, 1e-8, None)
        mse = float(np.mean(loo ** 2))
        if best is None or mse < best[0]:
            best = (mse, float(lam), alpha)
    _, lam, alpha = best
    pred_te = Phi_te @ (Phi_tr.T @ alpha)
    return dict(ridge=lam,
                train_acc=float(np.mean(np.sign(K @ alpha) == y_tr)),
                test_acc=float(np.mean(np.sign(pred_te) == y_te)))


def jac_rows(model: nn.Module, x: torch.Tensor) -> torch.Tensor:
    """Stack of per-sample Jacobians: shape (n, p)."""
    params = [p for p in model.parameters() if p.requires_grad]
    out_ = model(x)
    rows = []
    for i in range(out_.shape[0]):
        go = torch.zeros_like(out_)
        go[i, 0] = 1.0
        g = torch.autograd.grad(out_, params, grad_outputs=go, retain_graph=True)
        rows.append(torch.cat([gi.reshape(-1) for gi in g]))
    return torch.stack(rows)


