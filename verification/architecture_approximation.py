def s5_portrait() -> dict:
    out()
    out("  for every family we ask the same two questions of ONE dev-half question:")
    out("    (a) regression families: how good is the best polynomial / ReLU class?")
    out("        That is the finite-sample A -- the part of A a learner can feel.")
    out("    (b) classification families: how complex is the boundary?  We fit the")
    out("        labels with polynomial feature maps of increasing degree (ridge")
    out("        regression, the ridge picked by leave-one-out on the TRAINING set) and")
    out("        report the resulting test accuracy.  The degree at which the accuracy")
    out("        leaves chance is the degree the boundary needs.")
    out()
    table = {}
    for fam, (qid, ds) in PORTRAIT_Q.items():
        base = DATA / FAMILY_DIRS[fam] / ds
        train = torch.load(base / "train.pt", map_location="cpu", weights_only=True)
        test = torch.load(base / "test.pt", map_location="cpu", weights_only=True)
        xtr = train["x"].numpy()
        ytr = train["y"].numpy().squeeze()
        xte = test["x"].numpy()
        yte = test["y"].numpy().squeeze()
        d = xtr.shape[1]
        rec = dict(qid=qid, ds=ds, d=d, n=int(xtr.shape[0]))
        lo, hi = xtr.min(axis=0), xtr.max(axis=0)
        if fam in ("univar", "mvar"):
            rec["metric"] = "mse"
            class_specs = []
            for deg in (3, 7):
                ch = Cheb(deg, lo, hi)
                class_specs.append((f"poly deg {deg}", ch(xtr), ch(xte)))
            class_specs.append(("relu 256", relu_class(xtr, 256, 3, lo, hi),
                                relu_class(xte, 256, 3, lo, hi)))
            row = {}
            out(f"  {fam} ({qid}, d={d}, n={rec['n']}, metric=mse, "
                f"x in [{lo.min():.2f}, {hi.max():.2f}])")
            for cname, Phi_tr, Phi_te in class_specs:
                rel_tr = proj_error(Phi_tr, ytr)[1]
                rel_te = proj_error(Phi_te, yte)[1]
                row[cname] = dict(train_rel=rel_tr, test_rel=rel_te)
                out(f"      {cname:12s}: best fit of the training points {rel_tr:.3e} |"
                    f" best fit of the test points {rel_te:.3e}")
            rec["classes"] = row
        else:
            rec["metric"] = "ce"
            ytr_s = np.where(ytr > 0.5, 1.0, -1.0)
            yte_s = np.where(yte > 0.5, 1.0, -1.0)
            pos = float(np.mean(ytr_s > 0))
            ent = float(-(pos * math.log(max(pos, 1e-12))
                          + (1 - pos) * math.log(max(1 - pos, 1e-12))))
            ridges = [10.0 ** e for e in (-6, -4, -2, 0, 2, 4)]
            degs = []
            for deg in (1, 2, 3, 4, 6, 8, 12, 16):
                if math.comb(d + deg, d) > 6000:
                    break
                ch = Cheb(deg, lo, hi)
                r = ridge_label_eval(ch(xtr), ytr_s, ch(xte), yte_s, ridges)
                degs.append((deg, r["train_acc"], r["test_acc"], r["ridge"]))
                if r["test_acc"] >= 0.70:
                    break
            need = next((dg for dg, _, ta, _ in degs if ta >= 0.70), None)
            rec["poly_deg_acc"] = degs
            rec["min_degree_above_chance"] = need
            rec["label_entropy"] = ent
            out(f"  {fam} ({qid}, d={d}, n={rec['n']}, metric=ce, "
                f"x in [{lo.min():.2f}, {hi.max():.2f}])")
            out(f"      label entropy {ent:.3f} nats | class balance {pos:.3f}")
            out("      degree -> train acc / test acc / ridge: "
                + ", ".join(f"{dg}:{ta:.3f}/{va:.3f}" for dg, ta, va, _ in degs))
            out(f"      smallest polynomial degree that beats chance on the test set: "
                f"{need}")
        table[fam] = rec
    out()
    out("  reading: the degree at which a polynomial stops being chance is a cheap,")
    out("  honest proxy for 'how complicated is this boundary'.  The three families sit")
    out("  at different places -- which is exactly why one architecture rule cannot fit")
    out("  all of them.")
    out("  (bigram is left out on purpose: its target is a random law with an entropy")
    out("   floor, and the analysis lives in verification/bigram_estimation.py.)")
    result["S5"] = table
    return table


s5_portrait()

