head("S4b  the GP identity, checked exactly on a target drawn from the kernel")


def s4b_gp_identity() -> dict:
    out()
    out("  identity: for a GP prior with observation noise sigma^2, the posterior mean is")
    out("      mu(x) = k_x^T (K + sigma^2 I)^{-1} y")
    out("  and the posterior variance is")
    out("      var(x) = k(x,x) - k_x^T (K + sigma^2 I)^{-1} k_x")
    out("  so, IF the target is a draw from that kernel, the squared error of mu at a")
    out("  fresh test point has expectation var(x).  This is checkable: draw the target")
    out("  from the kernel itself, then compare.  (We normalise the kernel to unit")
    out("  diagonal so the numbers are on the scale of the target's variance; the")
    out("  identity does not care about the scaling.  A small sigma^2 is needed")
    out("  because the empirical NTK matrix is numerically rank deficient.)")
    out()

    base = DATA / FAM_DIR / DS
    cdir = base / "candidates" / SET_ID
    train = torch.load(base / "train.pt", map_location="cpu", weights_only=True)
    test = torch.load(base / "test.pt", map_location="cpu", weights_only=True)
    xtr = train["x"].numpy()
    xte = test["x"].numpy()
    c = cdir / CANDS["C"]
    mod = load_module(c / "model.py", "m_gp")
    torch.manual_seed(0)
    model = mod.Model()
    Jtr = jac_rows(model, torch.tensor(xtr, dtype=torch.float32))
    Jte = jac_rows(model, torch.tensor(xte, dtype=torch.float32))
    K = ((Jtr @ Jtr.T) / xtr.shape[0]).numpy()
    Ktt = ((Jte @ Jte.T) / xte.shape[0]).numpy()
    Kxt = ((Jte @ Jtr.T) / xtr.shape[0]).numpy()
    del Jtr, Jte

    dK = np.sqrt(np.clip(np.diag(K), 1e-30, None))
    dT = np.sqrt(np.clip(np.diag(Ktt), 1e-30, None))
    Kn = K / np.outer(dK, dK)
    Kttn = Ktt / np.outer(dT, dT)
    Kxtn = Kxt / np.outer(dT, dK)
    sigma2 = 1e-6
    n_tr = Kn.shape[0]
    Kv = Kn + sigma2 * np.eye(n_tr)
    sol = np.linalg.solve(Kv, Kxtn.T)
    post_cov = np.diag(Kttn) - np.sum(Kxtn * sol.T, axis=1)

    # draw the target from the JOINT kernel over (train, test) with the same noise,
    # so that the sample is a genuine GP function and not an artefact of stitching
    joint = np.zeros((n_tr + Kttn.shape[0],) * 2)
    joint[:n_tr, :n_tr] = Kn + sigma2 * np.eye(n_tr)
    joint[:n_tr, n_tr:] = Kxtn.T
    joint[n_tr:, :n_tr] = Kxtn
    joint[n_tr:, n_tr:] = Kttn
    jev, jV = np.linalg.eigh(joint)
    jkeep = jev > np.finfo(float).eps * max(joint.shape) * jev[-1]
    jsq = jV[:, jkeep] * np.sqrt(jev[jkeep])

    rng = np.random.default_rng(0)
    n_draw = 40 if QUICK else 200
    ratios, realised = [], []
    for _ in range(n_draw):
        z = jsq @ rng.normal(size=int(jkeep.sum()))
        y = z[:n_tr]
        f_test = z[n_tr:]
        mean = Kxtn @ (np.linalg.solve(Kv, y))   # the posterior mean = interpolant
        err = float(np.mean((f_test - mean) ** 2))
        realised.append(err)
        ratios.append(err / max(float(np.mean(post_cov)), 1e-30))
    realised = np.array(realised)
    ratios = np.array(ratios)
    out(f"  {n_draw} GP draws from the init NTK of candidate C (unit-diagonal kernel):")
    out(f"    analytic posterior variance at the test points : {np.mean(post_cov):.6e}")
    out(f"    realised mean squared error of the interpolant   : {realised.mean():.6e}")
    out(f"    ratio of the two MEANS (the tight check)         : "
        f"{realised.mean()/np.mean(post_cov):.4f}")
    out(f"    per-draw ratio: mean {ratios.mean():.4f}, sd {ratios.std(ddof=1):.4f}")
    out("    (the per-draw spread is large because the posterior covariance of a smooth")
    out("     kernel is nearly rank-1: the test points are strongly correlated, so the")
    out("     mean squared error over them is dominated by one common mode)")
    out()
    out("  reading: the realised error tracks the analytic posterior variance, so the")
    out("  lazy-limit error of a kernel method IS computable before training -- but")
    out("  only as a statement about the kernel's OWN prior.  For a deterministic target")
    out("  (our case) the posterior variance is a reference scale, not a prediction: the")
    out("  gap between the two is exactly the part of the target the kernel does not")
    out("  know how to represent.")
    result["S4b"] = dict(n_draws=n_draw, gp_post=float(np.mean(post_cov)),
                         realised=float(realised.mean()),
                         ratio_of_means=float(realised.mean() / np.mean(post_cov)),
                         ratio_mean=float(ratios.mean()),
                         ratio_sd=float(ratios.std(ddof=1)))
    return result["S4b"]


