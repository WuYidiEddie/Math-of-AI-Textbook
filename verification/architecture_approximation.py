def grid1() -> np.ndarray:
    return np.linspace(0, 1, GRID1)[:, None]


def grid2() -> np.ndarray:
    g = np.linspace(0, 1, GRID2)
    return np.stack(np.meshgrid(g, g, indexing="ij"), axis=-1).reshape(-1, 2)


def grid4() -> np.ndarray:
    g = np.linspace(0, 1, GRID4)
    return np.stack(np.meshgrid(*([g] * 4), indexing="ij"), axis=-1).reshape(-1, 4)


