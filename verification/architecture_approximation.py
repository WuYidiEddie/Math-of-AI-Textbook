def s4_rkhs() -> dict:
    out()
    out("  the claim: in the kernel (lazy) regime, the part of the target that the")
    out("  architecture cannot buy cheaply is measured by the SIZE of the coefficient")
    out("  that realises it.  Write the network at initialisation as f_w(x) = w^T phi(x)")
    out("  with phi(x) = J(x) the Jacobian, and let")
    out("      K = (1/n) J J^T = V Lam V^T        (n x n, eigenvalues = NTK eigenvalues)")
    out("  The minimum-norm weight vector that reproduces the target values y is")
    out("      w_hat = Phi^+ y  and   ||w_hat||^2 = y^T (J J^T)^+ y")
    out("                             = sum_j b_j^2 / lam_j^{(0)},  b = V^T y,")
    out("  where lam_j^{(0)} are the eigenvalues of J J^T, i.e. lam_j^{(0)} = n * lam_j.")
    out("  With the (1/n)-scaled K used above this becomes the estimator")
    out("      ||w_hat||^2  =  (1/n) sum_j b_j^2 / lam_j")
    out("  (the 1/n is a normalisation; the CONTENT is that the smaller lam_j is, the")
    out("   more expensive the target is in this architecture's currency.)")
    out()

    base = DATA / FAM_DIR / DS
    cdir = base / "candidates" / SET_ID
    train = torch.load(base / "train.pt", map_location="cpu", weights_only=True)
    test = torch.load(base / "test.pt", map_location="cpu", weights_only=True)
    out(f"  question {QID} (dev half: {is_dev(QID)}), dataset {DS}")
    xtr = train["x"].numpy()
    xte = test["x"].numpy()

    table = {}
    for letter, cid in CANDS.items():
        c = cdir / cid
        spec = json.loads((c / "candidate_spec.json").read_text(encoding="utf-8"))
        mod = load_module(c / "model.py", f"m_{cid}")
        lr = float(spec["optimizer"]["lr"])
        steps = int(spec["budget"]["training_steps"])
        torch.manual_seed(0)
        model = mod.Model()
        Jtr = jac_rows(model, torch.tensor(xtr, dtype=torch.float32))
        K = ((Jtr @ Jtr.T) / xtr.shape[0]).numpy()
        Jte = jac_rows(model, torch.tensor(xte, dtype=torch.float32))
        Ktt = ((Jte @ Jte.T) / xte.shape[0]).numpy()
        Kxt = ((Jte @ Jtr.T) / xtr.shape[0]).numpy()
        del Jtr, Jte
        evals, evecs = np.linalg.eigh(K)
        lam = np.clip(evals, 0.0, None)
        V = evecs
        cutoff = np.finfo(float).eps * max(K.shape) * lam[-1]
        keep = lam > cutoff
        rk = int(keep.sum())
        cond = float(lam[-1] / lam[keep][0]) if rk else float("inf")
        sv32 = np.linalg.svd(K.astype(np.float32), compute_uv=False)
        cut32 = np.finfo(np.float32).eps * max(K.shape) * sv32[0]
        rank32 = int((sv32 > cut32).sum())
        out()
        out(f"  candidate {letter} ({cid}): d={spec['model']['depth']} "
            f"w={spec['model']['width']} p={spec['trainable_parameter_count']}")
        out(f"    init NTK: lambda_max {lam[-1]:.4g} | numerical rank {rk}/256 in float64, "
            f"{rank32}/256 in float32 | cond(K) {cond:.3g}")
        out("    (the rank depends on the arithmetic: the training runs in float32, so")
        out("     the kernel it actually sees has the smaller rank)")
        win = 1.0 / (lr * steps)
        out(f"    learning window: lam >= 1/(lr*T) = {win:.1f}  "
            f"({int((lam * lr * steps >= 1.0).sum())}/256 directions are inside it)")
        rows = {}
        for tname in ("smooth  tanh(2x)^3 + sin(2 pi x)", "fast    sin(20 pi x)"):
            if tname.startswith("smooth"):
                ftr = np.tanh(2 * xtr[:, 0]) ** 3 + np.sin(2 * np.pi * xtr[:, 0])
                fte = np.tanh(2 * xte[:, 0]) ** 3 + np.sin(2 * np.pi * xte[:, 0])
            else:
                ftr = np.sin(20 * np.pi * xtr[:, 0])
                fte = np.sin(20 * np.pi * xte[:, 0])
            b = V.T @ ftr
            wnorm = float(np.sum((b[keep] ** 2) / lam[keep]) / xtr.shape[0])
            frozen = float(np.sum(b[(lam * lr * steps < 1.0) & keep] ** 2)
                           / max(float(np.sum(b[keep] ** 2)), 1e-30))
            alpha = np.linalg.lstsq(K, ftr, rcond=None)[0]
            lazy_tr = float(np.mean((K @ alpha - ftr) ** 2))
            lazy_te = float(np.mean((Kxt @ alpha - fte) ** 2))
            # GP posterior variance, computed on the UNIT-DIAGONAL normalised kernel.
            # The raw-scale formula k(x,x) - k_x' (K+s^2 I)^-1 k_x is a difference of
            # two nearly equal numbers, so with a nearly rank-deficient NTK it can
            # come out NEGATIVE (catastrophic cancellation).  After normalising the
            # diagonal to 1 the numbers are O(1) and the posterior variance is a
            # *relative* quantity, comparable with the lazy-limit error divided by
            # the target's own variance.
            dK = np.sqrt(np.clip(np.diag(K), 1e-30, None))
            dT = np.sqrt(np.clip(np.diag(Ktt), 1e-30, None))
            Kn = K / np.outer(dK, dK)
            Kttn = Ktt / np.outer(dT, dT)
            Kxtn = Kxt / np.outer(dT, dK)
            sig = 1e-6
            Kv = Kn + sig * np.eye(Kn.shape[0])
            sol = np.linalg.solve(Kv, Kxtn.T)
            post = np.diag(Kttn) - np.sum(Kxtn * sol.T, axis=1)
            gp_rel = float(np.mean(post))
            tvar = float(np.mean(fte ** 2))
            lazy_rel = lazy_te / max(tvar, 1e-30)
            rows[tname] = dict(weight_norm=wnorm, frozen=frozen, lazy_train=lazy_tr,
                               lazy_test=lazy_te, gp_post_rel=gp_rel,
                               lazy_test_rel=lazy_rel,
                               target_var=tvar)
            out(f"    target {tname}   (variance of the target on the test points: "
                f"{tvar:.4f})")
            out(f"      min-norm weight norm of the interpolant  ||w_hat||^2 = {wnorm:.4e}")
            out(f"      energy of the target OUTSIDE the learning window: {frozen*100:.2f}%")
            out(f"      lazy-limit (min-norm) interpolant: train MSE {lazy_tr:.4e}, "
                f"test MSE {lazy_te:.4e}")
            out(f"      the same two numbers, relative to the target's variance:")
            out(f"        lazy-limit relative test error                 "
                f"{lazy_rel:.4e}")
            out(f"        GP posterior variance of the same kernel        "
                f"{gp_rel:.4e}   (ratio {lazy_rel/gp_rel:.3f})")
            out(f"      (the GP number is what the SAME kernel would incur if the")
            out(f"       target were a draw from it; the gap is the part of this")
            out(f"       deterministic target the kernel does not know how to hold)")
        out()
        out("    reading:")
        out("      * the lazy-limit error is computable BEFORE training: it is the")
        out("        min-norm kernel interpolant's error, and (S4b) it equals the GP")
        out("        posterior variance when the target is a draw from the kernel;")
        out("      * for the FAST target the lazy interpolant is not merely worse, it is")
        out("        catastrophic: its test MSE exceeds the target's own variance, i.e.")
        out("        the smoothest function that fits the data is worse than predicting")
        out("        zero.  Feature learning is not optional on a fast target.")
        table[letter] = rows
    result["S4"] = table
    return table


