SPIRAL_Q = ("q_04316e", "spiral_classification", "spiralcls_2e1d80")
XOR_Q = ("q_07d60b", "xor_classification", "xorcls_a02077")
# official protocol per notes/bank-audit.csv
SPIRAL_OPT = dict(lr=3e-3, wd=1e-4, steps=4096, bs=16, name="Adagrad")
XOR_OPT = dict(lr=3e-3, wd=1e-4, steps=16384, bs=64, name="SGD")


def build_mlp(d_in: int, width: int, depth: int, out_dim: int) -> nn.Sequential:
    layers: list[nn.Module] = []
    for i in range(depth):
        layers.append(nn.Linear(d_in if i == 0 else width, width))
        layers.append(nn.ReLU())
    layers.append(nn.Linear(width, out_dim))
    return nn.Sequential(*layers)


def run_cls(ds, fam, depth, width, steps, bs, opt_cfg, seed) -> float:
    """Official protocol: minibatch sampling, the family's optimizer, test CE."""
    base = DATA / fam / ds
    tr = torch.load(base / "train.pt", map_location="cpu", weights_only=True)
    te = torch.load(base / "test.pt", map_location="cpu", weights_only=True)
    xtr, ytr, xte, yte = tr["x"], tr["y"], te["x"], te["y"]
    torch.manual_seed(seed)
    net = build_mlp(xtr.shape[1], width, depth, 2)
    if opt_cfg["name"] == "Adagrad":
        opt = torch.optim.Adagrad(net.parameters(), lr=opt_cfg["lr"],
                                  weight_decay=opt_cfg["wd"])
    else:
        opt = torch.optim.SGD(net.parameters(), lr=opt_cfg["lr"],
                               weight_decay=opt_cfg["wd"])
    n = xtr.shape[0]
    for _ in range(steps):
        idx = torch.randint(0, n, (bs,))
        opt.zero_grad()
        F.cross_entropy(net(xtr[idx]), ytr[idx]).backward()
        opt.step()
    with torch.no_grad():
        return float(F.cross_entropy(net(xte), yte))


def s2_architecture_sweep() -> dict:
    out()
    out("  our own model builder (plain ReLU MLP, no LayerNorm, no residual), the")
    out("  family's own optimizer / lr / budget from notes/bank-audit.csv, and the")
    out("  official evaluation (test CE).  Only depth and width are varied.")
    out()
    table = {}
    grids = [(1, 16), (2, 16), (3, 16), (1, 64), (2, 64), (3, 64)]
